def test_unregister_removes_only_selected_participant(client, activity_data):
    # Arrange
    activity_name = "Chess Club"
    email = "registered@mergington.edu"
    other_email = "other-student@mergington.edu"
    activity_data[activity_name]["participants"].append(other_email)

    # Act
    response = client.delete(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert response.json() == {"message": f"Unregistered {email} from {activity_name}"}
    assert activity_data[activity_name]["participants"] == [other_email]


